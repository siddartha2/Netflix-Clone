export const getMoviesByCategory = (category) =>
  movies.filter((m) => m.category === category)

export const getMovieById = (id) => movies.find((m) => m.id === Number(id))

export const getRecommended = (movie, count = 6) => {
  if (!movie) return []
  return movies
    .filter(
      (m) =>
        m.id !== movie.id && m.genre.some((g) => movie.genre.includes(g))
    )
    .slice(0, count)
}
